'use strict';

// 図の共通資産と、file:// / --embed-resources 対応の PlantUML ローダーを作る。
const fs = require('fs');
const path = require('path');
const COMMON_DIR = path.join(__dirname, '..', 'styles', 'browser');

function writeChanged(destination, content) {
  const data = Buffer.isBuffer(content) ? content : Buffer.from(content, 'utf8');
  if (fs.existsSync(destination) && fs.readFileSync(destination).equals(data)) { return; }
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, data);
}

function buildBrowserAssets(sourceDir, outputDir) {
  for (const name of fs.readdirSync(COMMON_DIR)) {
    writeChanged(path.join(outputDir, name), fs.readFileSync(path.join(COMMON_DIR, name)));
  }
  writeChanged(path.join(outputDir, 'docsfw-theme.js'), fs.readFileSync(path.join(__dirname, '..', 'styles', 'html', 'docsfw-theme.js')));
  const engineSource = fs.readFileSync(path.join(sourceDir, 'plantuml.js'));
  // 先読みしたアイコンも内部ローダーの完了表へ登録しないと、同名ファイルを再取得する。
  // 更新時に黙って file:// 対応を失わないよう、利用する内部契約を検査する。
  // see: https://unpkg.com/@plantuml/core@1.2026.7/plantuml.js
  if (!engineSource.includes('__pl_script_state')) {
    throw new Error('@plantuml/core のローダー契約が変わりました。アイコンの埋め込み処理を確認してください。');
  }
  const engine = engineSource.toString('base64');
  const libraries = ['viz-global.js', 'emoji.js', 'openiconic.js']
    .map(name => fs.readFileSync(path.join(sourceDir, name), 'utf8')).join('\n;\n');
  // ローカル ES モジュールの外部読み込みは file:// で CORS に阻まれる。
  // Blob URL の自己完結したモジュールと classic script を使い、import の相対参照を残さない。
  // see: https://developer.mozilla.org/en-US/docs/Web/JavaScript/Guide/Modules
  const license = fs.readFileSync(path.join(sourceDir, 'LICENSE'), 'utf8');
  // HTML の script 要素として埋め込むため、内容中の "</script" がタグを閉じないようにする。
  const escapeForInlineScript = (text) => text.replace(/<\/script/gi, '<\\/script');
  // engine の実評価は隠し iframe (sandbox="allow-scripts", 不透明オリジン) の中で行い、
  // メイン スレッドで巨大な PlantUML エンジンを直接 import・実行しない。
  // postMessage で描画要求を送り、SVG 文字列または失敗理由を受け取る。
  // see: node_modules/@plantuml/core/GITHUB_INTEGRATION.md (隠し iframe + postMessage の推奨構成)
  const frameHtml = '<!doctype html><html><head><meta charset="utf-8"></head><body>\n' +
    '<script>\n' + escapeForInlineScript(libraries) + '\n;\n' +
    'window.__pl_script_state = window.__pl_script_state || Object.create(null);\n' +
    '["emoji.js", "openiconic.js"].forEach(function (name) { window.__pl_script_state[name] = { state: "loaded" }; });\n' +
    '</script>\n' +
    '<script type="module">\n' +
    'let enginePromise;\n' +
    'function loadEngine() {\n' +
    // iPhone の Edge では data URL の import でページが停止し、Blob URL では描画できた。
    // see: https://github.com/Hondarer/plantuml-core-test/blob/main/docs/13.html
    // モジュールの追加処理と再描画に備え、Blob URL は iframe の破棄まで保持する。
    '  if (!enginePromise) {\n' +
    '    const bytes = Uint8Array.from(atob("' + engine + '"), c => c.charCodeAt(0));\n' +
    '    const url = URL.createObjectURL(new Blob([bytes], { type: "text/javascript" }));\n' +
    '    enginePromise = import(url);\n' +
    '  }\n' +
    '  return enginePromise;\n' +
    '}\n' +
    'window.addEventListener("message", function (event) {\n' +
    '  const requestId = event.data && event.data.requestId;\n' +
    '  if (!requestId) { return; }\n' +
    '  const lines = event.data.lines;\n' +
    '  const dark = !!event.data.dark;\n' +
    '  loadEngine().then(function (engine) {\n' +
    '    engine.renderToString(lines, function (svg) { parent.postMessage({ requestId, svg }, "*"); },\n' +
    '      function (error) { parent.postMessage({ requestId, error: String((error && error.message) || error) }, "*"); },\n' +
    '      { dark });\n' +
    '  }, function (error) {\n' +
    '    parent.postMessage({ requestId, error: String((error && error.message) || error) }, "*");\n' +
    '  });\n' +
    '});\n' +
    '</script>\n' +
    '</body></html>\n';
  // 単一 HTML だけを配布する場合もライセンス表記を残す。
  const loader = '/* Generated by build-browser-assets.js.\n' + license.replace(/\*\//g, '* /') + '\n*/\n' +
    '(function () {\n' +
    '  const FRAME_HTML = ' + JSON.stringify(frameHtml) + ';\n' +
    '  let framePromise;\n' +
    '  const pending = new Map();\n' +
    '  let seq = 0;\n' +
    '  function ensureFrame() {\n' +
    '    if (framePromise) { return framePromise; }\n' +
    '    const frame = document.createElement("iframe");\n' +
    '    frame.setAttribute("sandbox", "allow-scripts");\n' +
    '    frame.setAttribute("aria-hidden", "true");\n' +
    '    frame.style.display = "none";\n' +
    '    framePromise = new Promise(function (resolve) {\n' +
    '      frame.addEventListener("load", function () { resolve(frame); }, { once: true });\n' +
    '    });\n' +
    '    window.addEventListener("message", function (event) {\n' +
    '      if (event.source !== frame.contentWindow) { return; }\n' +
    '      const data = event.data || {};\n' +
    '      const entry = pending.get(data.requestId);\n' +
    '      if (!entry) { return; }\n' +
    '      pending.delete(data.requestId);\n' +
    '      if (data.error !== undefined) { entry.reject(data.error); } else { entry.resolve(data.svg); }\n' +
    '    });\n' +
    '    frame.srcdoc = FRAME_HTML;\n' +
    '    document.body.appendChild(frame);\n' +
    '    return framePromise;\n' +
    '  }\n' +
    '  window.docsfwLoadPlantuml = function () {\n' +
    '    return ensureFrame().then(function (frame) {\n' +
    '      return {\n' +
    '        renderToString(lines, onSuccess, onError, options) {\n' +
    '          const requestId = "p" + (++seq);\n' +
    '          pending.set(requestId, { resolve: onSuccess, reject: onError });\n' +
    '          frame.contentWindow.postMessage({ requestId, lines, dark: !!(options && options.dark) }, "*");\n' +
    '        },\n' +
    '      };\n' +
    '    });\n' +
    '  };\n' +
    '})();\n';
  writeChanged(path.join(outputDir, 'docsfw-plantuml-loader.js'), loader);
  writeChanged(path.join(outputDir, 'docsfw-plantuml-LICENSE.txt'), license);
}

module.exports = { buildBrowserAssets };
if (require.main === module) {
  if (process.argv.length !== 4) {
    console.error('Usage: node build-browser-assets.js <plantuml-core-dir> <output-dir>');
    process.exitCode = 1;
  } else {
    buildBrowserAssets(process.argv[2], process.argv[3]);
  }
}
